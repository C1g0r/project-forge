// OPERATIONAL CONSTITUTION ENGINE — Export Pipeline
// Exports constitution to Markdown, TXT, JSON, PDF

export type ExportFormat = 'markdown' | 'txt' | 'json' | 'pdf';

export interface ExportRequest {
  document: string;
  projectName: string;
  format: ExportFormat;
  lineCount?: number;
  wordCount?: number;
  sectionCount?: number;
  benchmarkScore?: number;
  grade?: string;
}

export interface ExportResult {
  content: string | Buffer;
  mimeType: string;
  filename: string;
  format: ExportFormat;
  byteSize: number;
}

function sanitizeFilename(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9\-_]/g, '_')
    .replace(/__+/g, '_')
    .replace(/^_|_$/g, '');
}

function getTimestamp(): string {
  return new Date().toISOString().slice(0, 10);
}

// === MARKDOWN EXPORT ===
function exportMarkdown(req: ExportRequest): ExportResult {
  const { document, projectName, lineCount, wordCount, sectionCount, benchmarkScore, grade } = req;

  const header = [
    `# ${projectName} — Operational Constitution`,
    '',
    `> Generated by Operational Constitution Engine`,
    `> Date: ${getTimestamp()}`,
    ...(lineCount ? [`> Lines: ${lineCount.toLocaleString()}`] : []),
    ...(wordCount ? [`> Words: ${wordCount.toLocaleString()}`] : []),
    ...(sectionCount ? [`> Sections: ${sectionCount}`] : []),
    ...(benchmarkScore !== undefined ? [`> Benchmark Score: ${benchmarkScore}/100 (Grade: ${grade})`] : []),
    '',
    '---',
    '',
  ].join('\n');

  const content = header + document;
  const filename = `${sanitizeFilename(projectName)}_constitution_${getTimestamp()}.md`;

  return {
    content,
    mimeType: 'text/markdown; charset=utf-8',
    filename,
    format: 'markdown',
    byteSize: Buffer.byteLength(content, 'utf-8'),
  };
}

// === TXT EXPORT ===
function exportTxt(req: ExportRequest): ExportResult {
  const { document, projectName, lineCount, wordCount, benchmarkScore, grade } = req;

  // Strip markdown formatting for plain text
  const plainText = document
    .replace(/^#{1,6}\s+/gm, '')     // Remove markdown headers
    .replace(/\*\*(.+?)\*\*/g, '$1') // Remove bold
    .replace(/\*(.+?)\*/g, '$1')     // Remove italic
    .replace(/`([^`]+)`/g, '$1')     // Remove inline code
    .replace(/^```[\w]*\n?/gm, '')   // Remove code fence open
    .replace(/^```\n?/gm, '')        // Remove code fence close
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1') // Remove links, keep text
    .replace(/^>\s+/gm, '  ');       // Remove blockquote markers

  const header = [
    `${'='.repeat(80)}`,
    `${projectName.toUpperCase()} — OPERATIONAL CONSTITUTION`,
    `${'='.repeat(80)}`,
    `Generated: ${getTimestamp()}`,
    ...(lineCount ? [`Lines: ${lineCount.toLocaleString()}`] : []),
    ...(wordCount ? [`Words: ${wordCount.toLocaleString()}`] : []),
    ...(benchmarkScore !== undefined ? [`Benchmark Score: ${benchmarkScore}/100 (Grade: ${grade})`] : []),
    `${'='.repeat(80)}`,
    '',
  ].join('\n');

  const content = header + plainText;
  const filename = `${sanitizeFilename(projectName)}_constitution_${getTimestamp()}.txt`;

  return {
    content,
    mimeType: 'text/plain; charset=utf-8',
    filename,
    format: 'txt',
    byteSize: Buffer.byteLength(content, 'utf-8'),
  };
}

// === JSON EXPORT ===
function exportJson(req: ExportRequest): ExportResult {
  const { document, projectName, lineCount, wordCount, sectionCount, benchmarkScore, grade } = req;

  // Parse sections from document
  const sections: { title: string; content: string }[] = [];
  const sectionPattern = /={40,}\n(.+?)\n={40,}\n([\s\S]*?)(?=={40,}|$)/g;
  let match;
  while ((match = sectionPattern.exec(document)) !== null) {
    sections.push({
      title: match[1].trim(),
      content: match[2].trim(),
    });
  }

  const payload = {
    meta: {
      projectName,
      generatedAt: new Date().toISOString(),
      engine: 'Operational Constitution Engine v1',
      benchmark: '1667Crow SYSTEM',
      format: 'oce-constitution-v1',
    },
    stats: {
      lineCount: lineCount ?? document.split('\n').length,
      wordCount: wordCount ?? document.split(/\s+/).filter(Boolean).length,
      sectionCount: sectionCount ?? sections.length,
      ...(benchmarkScore !== undefined ? { benchmarkScore, grade } : {}),
    },
    document: {
      fullText: document,
      sections: sections.length > 0 ? sections : [{ title: 'Full Document', content: document }],
    },
  };

  const content = JSON.stringify(payload, null, 2);
  const filename = `${sanitizeFilename(projectName)}_constitution_${getTimestamp()}.json`;

  return {
    content,
    mimeType: 'application/json; charset=utf-8',
    filename,
    format: 'json',
    byteSize: Buffer.byteLength(content, 'utf-8'),
  };
}

// === PDF EXPORT ===
async function exportPdf(req: ExportRequest): Promise<ExportResult> {
  const { document, projectName, lineCount, wordCount, benchmarkScore, grade } = req;

  try {
    // Dynamic import to avoid issues when pdfkit not installed
    const PDFDocument = (await import('pdfkit')).default;
    const chunks: Buffer[] = [];

    const doc = new PDFDocument({
      size: 'A4',
      margins: { top: 60, bottom: 60, left: 60, right: 60 },
      info: {
        Title: `${projectName} — Operational Constitution`,
        Author: 'Operational Constitution Engine',
        Subject: 'AI Operational Constitution',
        Creator: 'OCE v1',
      },
    });

    doc.on('data', (chunk: Buffer) => chunks.push(chunk));

    // Fonts
    const FONT_TITLE = 'Helvetica-Bold';
    const FONT_HEADING = 'Helvetica-Bold';
    const FONT_BODY = 'Helvetica';
    const FONT_MONO = 'Courier';

    // Colors
    const COLOR_DARK = '#1a1a2e';
    const COLOR_ACCENT = '#e94560';
    const COLOR_GRAY = '#666666';
    const COLOR_WHITE = '#ffffff';

    // Cover page
    doc.rect(0, 0, doc.page.width, doc.page.height).fill('#0f0e17');
    doc.fillColor(COLOR_ACCENT)
      .fontSize(28)
      .font(FONT_TITLE)
      .text(projectName.toUpperCase(), 60, 200, { align: 'center' });

    doc.fillColor(COLOR_WHITE)
      .fontSize(14)
      .font(FONT_BODY)
      .text('OPERATIONAL CONSTITUTION', 60, 240, { align: 'center' });

    doc.fillColor(COLOR_GRAY)
      .fontSize(10)
      .text(`Generated: ${getTimestamp()}`, 60, 300, { align: 'center' });

    if (lineCount) {
      doc.text(`${lineCount.toLocaleString()} lines`, 60, 318, { align: 'center' });
    }
    if (benchmarkScore !== undefined) {
      doc.fillColor(COLOR_ACCENT)
        .fontSize(16)
        .font(FONT_TITLE)
        .text(`Grade: ${grade} (${benchmarkScore}/100)`, 60, 345, { align: 'center' });
    }

    doc.fillColor(COLOR_GRAY)
      .fontSize(8)
      .font(FONT_BODY)
      .text('Operational Constitution Engine v1 | Benchmark: 1667Crow SYSTEM', 60, doc.page.height - 80, { align: 'center' });

    doc.addPage();
    doc.fillColor(COLOR_DARK);

    // Process document content
    const lines = document.split('\n');
    let inCodeBlock = false;
    let y = doc.y;
    const pageWidth = doc.page.width - 120;
    const maxY = doc.page.height - 80;

    for (const line of lines) {
      // Check for page overflow
      if (doc.y > maxY) {
        doc.addPage();
        doc.fillColor(COLOR_DARK);
      }

      const trimmed = line.trim();

      // Code fence
      if (trimmed.startsWith('```')) {
        inCodeBlock = !inCodeBlock;
        continue;
      }

      if (inCodeBlock) {
        doc.font(FONT_MONO)
          .fontSize(7)
          .fillColor('#2d6a4f')
          .text(line || ' ', { width: pageWidth, lineBreak: false });
        doc.moveDown(0.3);
        continue;
      }

      // Section separator
      if (/={40,}/.test(trimmed)) {
        doc.moveDown(0.5);
        doc.strokeColor(COLOR_ACCENT).lineWidth(1)
          .moveTo(60, doc.y)
          .lineTo(doc.page.width - 60, doc.y)
          .stroke();
        doc.moveDown(0.5);
        continue;
      }

      // Headers
      if (/^# /.test(line)) {
        doc.font(FONT_HEADING).fontSize(16).fillColor(COLOR_DARK)
          .text(line.replace(/^# /, ''), { width: pageWidth });
        doc.moveDown(0.5);
        continue;
      }
      if (/^## /.test(line)) {
        doc.font(FONT_HEADING).fontSize(13).fillColor(COLOR_DARK)
          .text(line.replace(/^## /, ''), { width: pageWidth });
        doc.moveDown(0.3);
        continue;
      }
      if (/^### /.test(line)) {
        doc.font(FONT_HEADING).fontSize(11).fillColor(COLOR_DARK)
          .text(line.replace(/^### /, ''), { width: pageWidth });
        doc.moveDown(0.3);
        continue;
      }

      // Bullet
      if (/^[-*]\s/.test(trimmed)) {
        doc.font(FONT_BODY).fontSize(9).fillColor(COLOR_DARK)
          .text(`• ${trimmed.slice(2)}`, { width: pageWidth - 10, indent: 10 });
        continue;
      }

      // Bold text
      if (/\*\*.+\*\*/.test(line)) {
        const processed = line.replace(/\*\*(.+?)\*\*/g, '$1');
        doc.font(FONT_HEADING).fontSize(9).fillColor(COLOR_DARK)
          .text(processed, { width: pageWidth });
        continue;
      }

      // Empty line
      if (!trimmed) {
        doc.moveDown(0.4);
        continue;
      }

      // Normal text
      doc.font(FONT_BODY).fontSize(9).fillColor(COLOR_DARK)
        .text(line, { width: pageWidth });
    }

    // Footer on last page
    doc.fillColor(COLOR_GRAY)
      .fontSize(8)
      .text(
        `${projectName} Operational Constitution | Generated ${getTimestamp()}`,
        60,
        doc.page.height - 40,
        { align: 'center' }
      );

    doc.end();

    const buffer = await new Promise<Buffer>((resolve, reject) => {
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);
    });

    const filename = `${sanitizeFilename(projectName)}_constitution_${getTimestamp()}.pdf`;

    return {
      content: buffer,
      mimeType: 'application/pdf',
      filename,
      format: 'pdf',
      byteSize: buffer.byteLength,
    };
  } catch (err) {
    // Fallback: return markdown if PDF generation fails
    console.error('PDF generation failed, falling back to markdown:', err);
    return exportMarkdown(req);
  }
}

// === MAIN EXPORT FUNCTION ===
export async function exportConstitution(req: ExportRequest): Promise<ExportResult> {
  switch (req.format) {
    case 'markdown':
      return exportMarkdown(req);
    case 'txt':
      return exportTxt(req);
    case 'json':
      return exportJson(req);
    case 'pdf':
      return exportPdf(req);
    default:
      return exportMarkdown(req);
  }
}

// Content-Type helper for express responses
export function getContentType(format: ExportFormat): string {
  switch (format) {
    case 'markdown': return 'text/markdown; charset=utf-8';
    case 'txt': return 'text/plain; charset=utf-8';
    case 'json': return 'application/json; charset=utf-8';
    case 'pdf': return 'application/pdf';
    default: return 'text/plain; charset=utf-8';
  }
}

// OPERATIONAL CONSTITUTION ENGINE — Document Compiler
// Integrates all 10 module outputs into one coherent constitution document

export interface ModuleOutput {
  moduleId: string;
  content: string;
  lineCount: number;
}

export interface CompileRequest {
  projectName: string;
  outputs: ModuleOutput[];
  complexity: 'minimal' | 'standard' | 'deep' | 'full';
}

export interface CompileResult {
  document: string;
  lineCount: number;
  sectionCount: number;
  wordCount: number;
  missingModules: string[];
}

// Canonical section order for the final constitution document
const SECTION_ORDER: string[] = [
  'constitution_compiler',   // preamble / header goes first
  'profile_architect',       // who the AI is
  'narrative_style',         // voice — declared before behavioral sections that use it
  'behavior_designer',       // core behavioral protocols
  'instruction_architect',   // greeting lock + format rules
  'capability_builder',      // capabilities table + code standards + tool protocol
  'protocol_generator',      // defensive protocols: injection defense, anti-drift, anti-leak
  'example_generator',       // examples + grounding
  'adversarial_lab',         // adversarial test suite (optional — only if present)
  'quality_export',          // benchmark scoring guide
];

const SECTION_SEPARATORS = '='.repeat(80);

function buildDocumentHeader(projectName: string): string {
  return `${SECTION_SEPARATORS}
${projectName.toUpperCase()} — OPERATIONAL CONSTITUTION
${SECTION_SEPARATORS}
Generated by the Operational Constitution Engine
Benchmark: 1667Crow SYSTEM v1667Crow SYSTEM
${SECTION_SEPARATORS}

`;
}

function buildTableOfContents(outputs: ModuleOutput[]): string {
  const orderedOutputs = getOrderedOutputs(outputs);
  const lines = ['## TABLE OF CONTENTS', ''];
  orderedOutputs.forEach((o, idx) => {
    const title = getModuleTitle(o.moduleId);
    lines.push(`${idx + 1}. ${title}`);
  });
  lines.push('');
  lines.push(SECTION_SEPARATORS);
  lines.push('');
  return lines.join('\n');
}

function getModuleTitle(moduleId: string): string {
  const titles: Record<string, string> = {
    profile_architect: 'IDENTITY & PROFILE ARCHITECTURE',
    instruction_architect: 'INSTRUCTION FRAMEWORK & RESPONSE FORMAT',
    behavior_designer: 'BEHAVIORAL ARCHITECTURE',
    capability_builder: 'CAPABILITIES & CODE STANDARDS',
    protocol_generator: 'DEFENSIVE PROTOCOLS',
    narrative_style: 'VOICE, STYLE & EMOTIONAL ARCHITECTURE',
    example_generator: 'EXAMPLES & GROUNDING',
    constitution_compiler: 'DOCUMENT FRAMEWORK & INTEGRATION',
    adversarial_lab: 'ADVERSARIAL TEST SUITE',
    quality_export: 'QUALITY FRAMEWORK & EXPORT',
  };
  return titles[moduleId] || moduleId.toUpperCase().replace(/_/g, ' ');
}

function getOrderedOutputs(outputs: ModuleOutput[]): ModuleOutput[] {
  const outputMap = new Map(outputs.map(o => [o.moduleId, o]));
  const ordered: ModuleOutput[] = [];

  for (const moduleId of SECTION_ORDER) {
    const output = outputMap.get(moduleId);
    if (output && output.content.trim()) {
      ordered.push(output);
    }
  }

  // Add any outputs not in the canonical order
  for (const output of outputs) {
    if (!SECTION_ORDER.includes(output.moduleId) && output.content.trim()) {
      ordered.push(output);
    }
  }

  return ordered;
}

function normalizeSection(content: string, moduleId: string): string {
  let normalized = content.trim();

  // Ensure the section starts with a visual separator if it doesn't already
  if (!normalized.startsWith('='.repeat(10))) {
    const title = getModuleTitle(moduleId);
    normalized = `${SECTION_SEPARATORS}\n${title}\n${SECTION_SEPARATORS}\n\n${normalized}`;
  }

  return normalized;
}

function detectMissingModules(outputs: ModuleOutput[]): string[] {
  const presentModules = new Set(outputs.map(o => o.moduleId));
  const coreMandatory = [
    'profile_architect',
    'behavior_designer',
    'instruction_architect',
    'capability_builder',
    'protocol_generator',
  ];

  return coreMandatory.filter(m => !presentModules.has(m));
}

function countWords(text: string): number {
  return text.split(/\s+/).filter(w => w.length > 0).length;
}

function countLines(text: string): number {
  return text.split('\n').length;
}

function countSections(text: string): number {
  return (text.match(/^={10,}/gm) || []).length;
}

export function compileConstitution(req: CompileRequest): CompileResult {
  const { projectName, outputs, complexity } = req;

  if (!outputs || outputs.length === 0) {
    return {
      document: '',
      lineCount: 0,
      sectionCount: 0,
      wordCount: 0,
      missingModules: detectMissingModules([]),
    };
  }

  const missingModules = detectMissingModules(outputs);
  const orderedOutputs = getOrderedOutputs(outputs);

  const parts: string[] = [];

  // Document header
  parts.push(buildDocumentHeader(projectName));

  // Table of contents (only for standard+ complexity)
  if (complexity !== 'minimal') {
    parts.push(buildTableOfContents(outputs));
  }

  // Compile each module section
  for (const output of orderedOutputs) {
    const normalized = normalizeSection(output.content, output.moduleId);
    parts.push(normalized);
    parts.push('\n\n');
  }

  // Final document footer
  parts.push(`\n${SECTION_SEPARATORS}\n`);
  parts.push(`END OF OPERATIONAL CONSTITUTION — ${projectName.toUpperCase()}\n`);
  parts.push(`${SECTION_SEPARATORS}\n`);

  const document = parts.join('\n');

  return {
    document,
    lineCount: countLines(document),
    sectionCount: countSections(document),
    wordCount: countWords(document),
    missingModules,
  };
}

// Quick compile for preview — truncates long sections
export function compilePreview(req: CompileRequest): CompileResult {
  const truncated = req.outputs.map(o => ({
    ...o,
    content: o.content.length > 2000
      ? o.content.slice(0, 2000) + '\n...[truncated for preview]...'
      : o.content,
  }));

  return compileConstitution({ ...req, outputs: truncated });
}

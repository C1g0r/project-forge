import type { DocumentBlueprint } from "../pipeline/architect.ts";
import type { ValidationReport, Issue } from "../pipeline/validator.ts";

export function exportValidationReport(
  blueprint: DocumentBlueprint,
  report: ValidationReport
): string {
  const lines: string[] = [];
  const date = new Date().toLocaleDateString("pt-PT");

  lines.push(`# Validation Report — ${blueprint.title}`);
  lines.push("");
  lines.push(`> **Document:** ${blueprint.title}`);
  lines.push(`> **Audience:** ${blueprint.audience}`);
  lines.push(`> **Validated on:** ${date}`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Score
  const bar = scoreBar(report.score);
  lines.push(`## Overall Score`);
  lines.push("");
  lines.push(`**${report.score}/100** ${bar}`);
  lines.push("");
  lines.push(`> ${report.overallVerdict}`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Contradictions
  if (report.contradictions.length > 0) {
    lines.push(`## Contradictions (${report.contradictions.length})`);
    lines.push("");
    report.contradictions.forEach((issue, i) => {
      lines.push(...formatIssue(i + 1, issue));
    });
    lines.push("---");
    lines.push("");
  }

  // Gaps
  if (report.gaps.length > 0) {
    lines.push(`## Content Gaps (${report.gaps.length})`);
    lines.push("");
    report.gaps.forEach((issue, i) => {
      lines.push(...formatIssue(i + 1, issue));
    });
    lines.push("---");
    lines.push("");
  }

  // Repetitions
  if (report.repetitions.length > 0) {
    lines.push(`## Repetitions (${report.repetitions.length})`);
    lines.push("");
    report.repetitions.forEach((issue, i) => {
      lines.push(...formatIssue(i + 1, issue));
    });
    lines.push("---");
    lines.push("");
  }

  // Suggestions
  if (report.suggestions.length > 0) {
    lines.push(`## Improvement Suggestions`);
    lines.push("");
    report.suggestions.forEach((s) => {
      lines.push(`- ${s}`);
    });
    lines.push("");
    lines.push("---");
    lines.push("");
  }

  lines.push(`*Generated by PROJECT FORGE · ${date}*`);

  return lines.join("\n");
}

function formatIssue(n: number, issue: Issue): string[] {
  const severityLabel = {
    high: "🔴 HIGH",
    medium: "🟡 MEDIUM",
    low: "🟢 LOW",
  }[issue.severity];

  return [
    `### ${n}. ${issue.location}`,
    "",
    `**Severity:** ${severityLabel}`,
    "",
    `**Issue:** ${issue.description}`,
    "",
    `**Suggestion:** ${issue.suggestion}`,
    "",
  ];
}

function scoreBar(score: number): string {
  const filled = Math.round(score / 10);
  return "█".repeat(filled) + "░".repeat(10 - filled);
}
